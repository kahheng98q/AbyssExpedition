"""Original offline combat cues. Python standard library; no source samples."""
from pathlib import Path
import hashlib
import json
import math
import random
import struct
import wave

ROOT = Path(__file__).resolve().parents[1]
RATE = 44100
SEED = 20261019
DURATIONS = {"attack_arc": .09, "attack_straight": .10, "attack_homing": .12,
             "hit": .065, "kill": .13, "hero_hurt": .115, "level": .156}

def synthesize(cue, seconds, rng):
    values = []
    previous = 0.0
    for index in range(int(seconds * RATE)):
        t = index / RATE
        u = t / seconds
        noise = rng.uniform(-1, 1)
        edge = noise - previous
        previous = noise
        attack = min(1, t / .003)
        envelope = attack * (1-u)**2
        if cue == "attack_arc":
            sample = (.7*edge + .3*math.sin(2*math.pi*(1800*t-5000*t*t))) * envelope
        elif cue == "attack_straight":
            sample = (math.sin(2*math.pi*720*t)+.35*math.sin(2*math.pi*1443*t)) * envelope * math.exp(-18*t)
        elif cue == "attack_homing":
            sample = sum(math.sin(2*math.pi*f*t) for f in (523.25, 784.0, 1046.5)) * envelope
        elif cue == "hit":
            sample = (.6*noise + math.sin(2*math.pi*(160*t-500*t*t))) * envelope * math.exp(-20*t)
        elif cue == "kill":
            sample = (math.sin(2*math.pi*(900*t-2000*t*t))+.7*math.sin(2*math.pi*360*t)+.2*noise) * envelope
        elif cue == "hero_hurt":
            sample = (math.sin(2*math.pi*125*t)+.7*math.sin(2*math.pi*177*t)+.2*noise)*envelope
        else:
            sample = 0.0
            for j, f in enumerate((523.25, 659.25, 783.99)):
                local = t-j*.036
                if local >= 0:
                    gate = min(1, local/.003) * max(0, 1-local/(seconds-j*.036))**1.5
                    sample += math.sin(2*math.pi*f*local)*gate
            sample *= max(0, 1-u)**.5
        values.append(sample)
    peak = max(map(abs, values))
    return b"".join(struct.pack("<h", round(v/peak*.48*32767)) for v in values)

def main():
    directory = ROOT / "assets/audio"
    directory.mkdir(exist_ok=True)
    manifest = {"origin":"original mathematical synthesis; no samples/downloads", "private_seed":SEED,
                "sample_rate":RATE,"channels":1,"bits":16,"source_peak_budget":.5,"cues":{}}
    rng = random.Random(SEED)
    for cue, duration in DURATIONS.items():
        path = directory / (cue+".wav")
        pcm = synthesize(cue,duration,rng)
        with wave.open(str(path),"wb") as out:
            out.setparams((1,2,RATE,0,"NONE","not compressed"))
            out.writeframes(pcm)
        import_path = Path(str(path)+".import")
        if import_path.exists():
            settings = import_path.read_text(encoding="utf-8").replace("compress/mode=2", "compress/mode=0").replace("compress/mode=1", "compress/mode=0")
        else:
            settings = ('[remap]\nimporter="wav"\ntype="AudioStreamWAV"\n\n[deps]\nsource_file="res://assets/audio/'+cue+'.wav"\n\n[params]\nforce/8_bit=false\nforce/mono=true\nforce/max_rate=false\nedit/trim=false\nedit/normalize=false\nedit/loop_mode=0\ncompress/mode=0\n')
        import_path.write_text(settings,encoding="utf-8")
        manifest["cues"][cue] = {"seconds":len(pcm)/2/RATE,"sha256":hashlib.sha256(path.read_bytes()).hexdigest(),
                                   "peak":max(abs(x[0]) for x in struct.iter_unpack("<h",pcm))/32768}
    (directory/"generated-manifest.json").write_text(json.dumps(manifest,indent=2)+"\n",encoding="utf-8")
    provenance=ROOT/"assets/provenance.md"
    existing=provenance.read_bytes()
    start="<!-- combat-audio-generated:start -->"
    end="<!-- combat-audio-generated:end -->"
    if start.encode() in existing: existing=existing[:existing.index(start.encode())]+existing[existing.index(end.encode())+len(end):]
    text="\n\n"+start+"\n## Original combat audio — 2026-10-19\n\n"
    text+="Generated by tools/generate_combat_audio.py using only math/random/struct/wave. No external samples or downloads. Private synthesis seed 20261019; runtime never synthesizes or consumes gameplay RNG. Mono 44.1kHz/16-bit PCM, nonlooping; source peak target0.48 (budget0.5). Manifest stores measured lengths/peaks. Listening and real mix acceptance pending.\n\n"
    for cue,entry in manifest["cues"].items(): text+=f"- {cue}: {entry['seconds']:.6f}s; SHA256 {entry['sha256']}\n"
    provenance.write_bytes(existing.rstrip()+(text+end+"\n").encode("utf-8"))
    print("Generated7 original PCM cues; source peaks <=0.5; level <=0.160s.")

if __name__ == "__main__": main()
